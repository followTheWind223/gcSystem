import { test, expect } from '@playwright/test'

async function login(page, target = '/me/orders') {
  await page.goto(`/login?redirect=${encodeURIComponent(target)}`)
  await page.getByRole('button', { name: '填入演示账号' }).click()
  await page.getByRole('button', { name: '登 录', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(target.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')))
}
async function scenario(page, value) {
  await page.getByRole('button', { name: '演示模式' }).click()
  await page.getByLabel('测试场景').selectOption(value)
  await page.getByRole('button', { name: '收起', exact: true }).click()
}
async function directCheckout(page) {
  await login(page, '/props/1001')
  await page.getByRole('button', { name: '立即购买', exact: true }).click()
  await expect(page.getByRole('heading', { name: '交付信息', exact: true })).toBeVisible()
  await page.getByLabel('游戏账号', { exact: true }).fill('demo_account')
  for (const server of await page.getByRole('combobox', { name: /游戏区服/ }).all()) { await server.press('ArrowDown'); await page.getByRole('option', { name: '一区', exact: true }).click() }
  await page.getByLabel('角色名称', { exact: true }).fill('星海旅人')
  await page.getByRole('checkbox', { name: '我已确认当前价格、数量及交付信息' }).check()
}

test('home, category filters, sorting, detail and empty/error states', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /下一场冒险，.*从好装备开始。/ })).toBeVisible()
  await expect(page.locator('.product-card')).toHaveCount(6)
  await page.getByRole('link', { name: /霓虹战线.*未来战场/ }).click()
  await expect(page.locator('.product-card')).toHaveCount(3)
  await page.locator('.shop-select').click()
  await page.getByRole('option', { name: '价格从低到高', exact: true }).click()
  await expect(page.locator('.product-name').first()).toHaveText('能量结晶')
  await page.locator('.product-name').first().click()
  await expect(page.getByRole('heading', { name: '能量结晶', exact: true }).first()).toBeVisible()
  await scenario(page, 'stockout')
  await expect(page.getByRole('button', { name: '立即购买', exact: true })).toBeDisabled()
  await scenario(page, 'off-shelf')
  await expect(page.getByRole('heading', { name: '内容暂不可用' })).toBeVisible()
  await page.getByRole('link', { name: '全部道具', exact: true }).first().click()
  await scenario(page, 'empty')
  await expect(page.getByRole('heading', { name: '暂时没有匹配的道具' })).toBeVisible()
  await scenario(page, 'network')
  await expect(page.getByRole('heading', { name: '暂时无法加载' })).toBeVisible()
  expect(errors).toEqual([])
})

