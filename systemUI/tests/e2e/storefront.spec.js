test('refresh and server session expiration both require a new login', async ({ page }) => {
  await login(page, '/me/orders')
  await page.reload()
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.getByRole('button', { name: '填入演示账号' }).click()
  await page.getByRole('button', { name: '登 录', exact: true }).click()
  await expect(page.locator('.order-card')).toHaveCount(2)
  await scenario(page, 'session-expired')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await expect(page.locator('.cart-count')).toHaveCount(0)
})

test('desktop and mobile routes fit viewport and render without runtime errors', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({ width: 1440, height: 1060 })
  await page.goto('/')
  await expect(page.locator('.product-card')).toHaveCount(6)
  await page.screenshot({ path: 'test-results/home-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  for (const path of ['/', '/props', '/props/1001', '/login', '/register']) {
    await page.goto(path)
    await page.waitForTimeout(600)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), path).toBeTruthy()
  }
  await page.goto('/')
  await expect(page.locator('.product-card')).toHaveCount(6)
  await page.screenshot({ path: 'test-results/home-mobile.png', fullPage: true })
  await login(page, '/cart')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/cart-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
