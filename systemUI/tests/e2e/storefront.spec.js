test('quote changes require renewed confirmation and expired payment cannot proceed', async ({ page }) => {
  await directCheckout(page)
  await scenario(page, 'quote-changed')
  await page.getByRole('button', { name: '提交订单', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('商品价格发生变化')
  await expect(page.getByRole('button', { name: '提交订单', exact: true })).toBeDisabled()
  await scenario(page, 'normal')
  await page.getByRole('button', { name: '重新获取报价' }).click()
  await expect(page.getByRole('checkbox', { name: '我已确认当前价格、数量及交付信息' })).not.toBeChecked()
  await page.getByRole('checkbox', { name: '我已确认当前价格、数量及交付信息' }).check()
  await page.getByRole('button', { name: '提交订单', exact: true }).click()
  await expect(page).toHaveURL(/\/pay$/)
  await scenario(page, 'order-expired')
  await expect(page.getByRole('heading', { name: '支付时间已结束' })).toBeVisible()
  await expect(page.getByRole('button', { name: '去支付' })).toHaveCount(0)
})

